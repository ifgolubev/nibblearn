/** Names accepted by `contentIcons`. */
export const contentIconNames = Object.keys(contentIcons);

/** Resolve a kebab-case icon name to a component (null when unknown). */
export function resolveContentIcon(name: string | undefined): LucideIcon | null {
  if (!name) return null;
  const key = name.toLowerCase();
  // Own keys only, so names like "constructor" never resolve to Object.prototype members.
  return Object.prototype.hasOwnProperty.call(contentIcons, key)
    ? (contentIcons[key] ?? null)
    : null;
}
