// Extracts the JSDoc comment above each schema field into packages/core/src/schema/field-docs.generated.ts.
// Run after editing schema comments: node scripts/extract-field-docs.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const schemaDir = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "packages",
  "core",
  "src",
  "schema",
);
const docRe = /\/\*\*((?:(?!\*\/)[\s\S])*?)\*\/\s*\n\s*(\w+)\s*:/g;
const clean = (raw) =>
  raw
    .split("\n")
    .map((l) => l.replace(/^\s*\*\s?/, "").trim())
    .filter(Boolean)
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();

// Files that define several module types: each `export const <name>Schema` section belongs to
// the module type named here, so equal field names (title, text…) keep their own docs.
const multiTypeFiles = {
  "content-blocks.ts": {
    callout: "callout",
    accordionItem: "accordion",
    accordion: "accordion",
    tab: "tabs",
    tabs: "tabs",
    carouselSlide: "carousel",
    carousel: "carousel",
    column: "columns",
    columns: "columns",
  },
};

function extractSource(src) {
  const out = {};
  for (const m of src.matchAll(docRe)) {
    const key = m[2];
    if (!(key in out)) out[key] = clean(m[1]);
  }
  return out;
}

const extract = (file) => extractSource(readFileSync(file, "utf8"));

/** Split a multi-type file at each `export const <name>Schema` and group docs by module type. */
function extractByType(file, map) {
  const src = readFileSync(file, "utf8");
  const starts = [...src.matchAll(/^export const (\w+)Schema\b/gm)];
  const out = {};
  starts.forEach((m, i) => {
    const type = map[m[1]];
    if (!type) throw new Error(`${file}: no module type for "${m[1]}Schema" in multiTypeFiles`);
    const section = src.slice(m.index, starts[i + 1]?.index ?? src.length);
    out[type] = { ...extractSource(section), ...out[type] };
  });
  return out;
}

const global = {
  ...extract(join(schemaDir, "lesson.ts")),
  ...extract(join(schemaDir, "common.ts")),
};
const byType = {};
for (const f of readdirSync(join(schemaDir, "modules")).sort()) {
  if (!f.endsWith(".ts") || f === "index.ts") continue;
  if (multiTypeFiles[f])
    Object.assign(byType, extractByType(join(schemaDir, "modules", f), multiTypeFiles[f]));
  else byType[f.replace(/\.ts$/, "")] = extract(join(schemaDir, "modules", f));
}
const body = `// Generated by scripts/extract-field-docs.mjs from the JSDoc comments in the schema files. Do not edit.
export const fieldDocs: {
  readonly global: Readonly<Record<string, string>>;
  readonly byType: Readonly<Record<string, Readonly<Record<string, string>>>>;
} = ${JSON.stringify({ global, byType }, null, 2)};
`;
writeFileSync(join(schemaDir, "field-docs.generated.ts"), body);
console.log(
  `field docs: ${Object.keys(global).length} global, ${Object.values(byType).reduce((n, o) => n + Object.keys(o).length, 0)} module fields`,
);
